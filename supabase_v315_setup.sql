-- Supabase Auth kullanıcıları auth.users tablosunda tutulur; parola bu tabloda saklanmaz.

create table if not exists public.saved_coupons (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  mode text not null,
  legs jsonb not null default '[]'::jsonb,
  status text not null default 'ACIK' check (status in ('ACIK','KAZANDI','KAYBETTI','IPTAL')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists saved_coupons_user_created_idx
  on public.saved_coupons (user_id, created_at desc);

alter table public.saved_coupons enable row level security;

drop policy if exists "users_select_own_coupons" on public.saved_coupons;
create policy "users_select_own_coupons" on public.saved_coupons
for select to authenticated using (auth.uid() = user_id);

drop policy if exists "users_insert_own_coupons" on public.saved_coupons;
create policy "users_insert_own_coupons" on public.saved_coupons
for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "users_update_own_coupons" on public.saved_coupons;
create policy "users_update_own_coupons" on public.saved_coupons
for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "users_delete_own_coupons" on public.saved_coupons;
create policy "users_delete_own_coupons" on public.saved_coupons
for delete to authenticated using (auth.uid() = user_id);
